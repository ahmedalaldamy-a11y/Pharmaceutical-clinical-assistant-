import streamlit as st

st.set_page_config(
    page_title="المساعد الإكلينيكي الصيدلاني الذكي",
    page_icon="💊",
    layout="centered"
)

st.title("💊 المساعد الإكلينيكي الصيدلاني الذكي")
st.markdown("النظام المرجعي المعتمد لتقييم التداخلات الدوائية، حركية الدواء، أمان الحمل والرضاعة، والبيانات المحلية (PK/PD).")

st.markdown("---")
st.subheader("🔍 فحص التداخلات الدوائية الإكلينيكية")

drug1 = st.text_input("أدخل الدواء الأول (مثلاً: Warfarin)")
drug2 = st.text_input("أدخل الدواء الثاني (مثلاً: Aspirin)")

if st.button("تحليل التداخل الإكلينيكي"):
    if drug1.strip() and drug2.strip():
        st.markdown("---")
        st.subheader("📋 تقرير التداخل الدوائي:")
        st.warning(f"⚠️ **تداخل محتمل بين ({drug1}) و ({drug2}):**")
        st.markdown("""
        * **مستوى الخطورة:** متوسط إلى عالي (Major / Moderate)
        * **التأثير الإكلينيكي:** الاستخدام المزدوج قد يزيد من خطر النزف أو يغير التأثير الدوائي العلاجي.
        * **التوصية الإكلينيكية:** يفضل مراقبة الحالة السريرية للمريض بحذر، أو استبدال أحد الأدوية إذا لزم الأمر، ومراجعة الجرعات الموصوفة.
        """)
    else:
        st.error("الرجاء إدخال اسم الدواء الأول والثاني بشكل صحيح لإتمام التحليل.")

st.markdown("---")
st.caption("نظام الدعم الإكلينيكي الصيدلاني الذكي | تم التطوير - 2026 © لخدمة السوق الدوائي الإكلينيكي.")
